"""Generate the public server attribute lookup from the locked Gecko SDK catalogue and reviewed R8 supplements."""
from argparse import ArgumentParser
from pathlib import Path
import json

from generate import verified_files
from r8_attributes import additional

HERE = Path(__file__).resolve().parent
TARGET = HERE.parents[1] / "crates/zigbee-zcl/src/standard_attributes.rs"
TYPES = {"BOOLEAN": 0x10, "ENUM8": 0x30, "ENUM16": 0x31, "FLOAT_SINGLE": 0x39,
         "UTC_TIME": 0xe2, "CHAR_STRING": 0x42}
for size in range(1, 9):
    for name, start in (("INT{}U", 0x20), ("INT{}S", 0x28), ("BITMAP{}", 0x18), ("DATA{}", 0x08)):
        TYPES[name.format(8 * size)] = start + size - 1


def generate(source):
    records = {}
    def add(cluster, attr, ty, name):
        # The public Basic identity strings are the only free-text fields admitted to telemetry.
        if ty == 0x42 and (cluster != 0 or attr not in (4, 5, 6, 0x4000)):
            return
        key = (cluster, attr)
        if key in records and records[key][0] != ty:
            raise ValueError(f"conflicting wire type at {key}")
        records.setdefault(key, (ty, name))

    documents = verified_files(source, False).values()
    global_attrs = [a for doc in documents for a in doc.findall("global/attribute")
                    if a.get("side") == "server"]
    for doc in documents:
        for c in [*doc.findall("cluster"), *doc.findall("clusterExtension")]:
            cluster = int(c.get("code") or c.findtext("code"), 0)
            if cluster >= 0xfc00 or c.get("manufacturerCode"):
                continue
            attrs = c.findall("attribute")
            if c.tag == "cluster":
                attrs = global_attrs + attrs
            for a in attrs:
                ty = TYPES.get(a.get("type"))
                if a.get("side") != "server" or a.get("manufacturerCode") or ty is None or a.get("array") == "true":
                    continue
                attr = int(a.attrib["code"], 0)
                name = " ".join((a.text or a.get("define", "")).split())
                add(cluster, attr, ty, name)
    for row in additional():
        add(*row)
    table = "\n".join(f"    (0x{cluster:04x}, 0x{attr:04x}, 0x{ty:02x}, {json.dumps(name, ensure_ascii=False)}),"
                      for (cluster, attr), (ty, name) in sorted(records.items()))
    return """// @generated by tools/zcl/standard_attributes.py from the locked Gecko SDK XML and reviewed R8 supplements.
// Derived from Silicon Labs XML, Copyright (c) 2008,2020 Silicon Labs.
// SPDX-License-Identifier: Apache-2.0
//! Public scalar server attributes. An interview or a successful device
//! response supplies the evidence that a particular device implements one.

#[rustfmt::skip]
const ATTRIBUTES: &[(u16, u16, u8, &str)] = &[
""" + table + """
];

pub fn wire_type(cluster: u16, attribute: u16) -> Option<u8> {
    let index = ATTRIBUTES.binary_search_by_key(&(cluster, attribute), |row| (row.0, row.1)).ok()?;
    Some(ATTRIBUTES[index].2)
}

pub fn attributes(cluster: u16) -> impl Iterator<Item = (u16, u8, &'static str)> {
    let index = ATTRIBUTES.partition_point(|row| row.0 < cluster);
    ATTRIBUTES[index..].iter().take_while(move |row| row.0 == cluster)
        .map(|&(_, id, ty, name)| (id, ty, name))
}
"""


if __name__ == "__main__":
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = generate(args.source)
    if args.check:
        if TARGET.read_text() != data:
            parser.exit(1, "generated server attribute table differs\n")
    else:
        TARGET.write_text(data)
